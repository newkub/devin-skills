// Decision: the generated guides are data, not files checked in by hand, so the wording
// tracks the real tool names and command surface. Validation reads the files back from
// disk, which is what makes it a real check of the artifact an agent will load.

export type SkillDef = {
  name: string
  description: string
  related: string[]
  body: string
}

const ENTRY = `## Goal

Keep an agent-readable index of a project's code, so an agent can search a symbol, read its exact location and provenance, and see what a change affected without re-reading the tree.

## Scope

One project root containing \`watch-references.json\`. Generated by \`watch-ref skills generate\`; use it when the project is already initialised.

## Execute

### 1. Start The Server

Run \`watch-ref serve\` from the project root. The server exposes the core index over stdio; the CLI is not required while it runs. Diagnostics go to stderr and never to the protocol stream.

1. MCP resources are stable and documented: \`watchref://index\`, \`watchref://status\`, \`watchref://categories\`, \`watchref://changes\`, \`watchref://feedback\`, \`watchref://evidence\`, and \`watchref://references/{category}\`.
2. Read \`watchref://status\` first. If \`lastScanAt\` is null, call \`refresh_references\` before searching.

### 2. Find Things

1. \`search_references\` — query text with optional \`category\`, \`file\`, and \`limit\`. Results carry \`file\`, \`startLine\`, \`endLine\`, and \`provenance\`.
2. \`inspect_symbol\` — resolve a name; prefer it when you know the symbol, not the text.
3. \`reference_details\` — fetch one reference by id, including provenance and metadata.
4. \`affected_references\` — given a changed file, list references inside it and architecture references that point at it.
5. \`system_status\` — counts, watcher health, and last error.

Tool list: \`search_references\`, \`inspect_symbol\`, \`reference_details\`, \`system_status\`, \`refresh_references\`, \`affected_references\`, \`run_checks\`.

### 3. Interpret Results

1. Every reference is a location, not a judgment. Read the file before changing it.
2. \`provenance.generator\` says where it came from: \`ast-grep\`, \`derive\`, \`file\`, \`diagnostic\`, \`architecture\`, or \`visual\`.
3. A \`diagnostic\` reference means the file failed to parse or read. Fix that file first; other refs in it may be stale.
4. \`watchref://changes\` is the most recent change set, not a history.

### 4. Verify

1. After a code change, call \`refresh_references\` and confirm \`watchref://status\` shows a newer \`lastScanAt\`.
2. Run \`run_checks\` to execute the project's configured commands. A non-zero exit is a failure, not a warning.
3. If a query returns nothing for a symbol you can see in the file, report the miss instead of guessing: the file may be excluded or too large.

## Rules

1. Never edit a file from a reference alone: read it first.
2. Treat a \`diagnostic\` reference as a parse failure, not as content to copy.
3. Never invent a location; an empty result is a finding, not a prompt to guess.

## Expected Outcome

A symbol lookup returns its exact file, line range, and provenance, and a changed file lists the references it affects.
`

