export const SKILL_DEFS: SkillDef[] = [
  {
    name: "watch-references",
    description: "Search and inspect a project's live code references over MCP",
    related: ["watch-references-feedback", "watch-references-maintenance"],
    body: ENTRY,
  },
  {
    name: "watch-references-feedback",
    description: "Submit feedback, request an authorized fix, and verify the result",
    related: ["watch-references", "watch-references-maintenance"],
    body: FEEDBACK,
  },
  {
    name: "watch-references-maintenance",
    description: "Maintain categories, parsers, evidence, and generated guides",
    related: ["watch-references", "watch-references-feedback"],
    body: MAINTENANCE,
  },
]

export function renderSkill(def: SkillDef): string {
  const related = def.related.map((name) => `  - ${name}`).join("\n")
  return [
    "---",
    `name: ${def.name}`,
    `description: ${def.description}`,
    "related:",
    related,
    "---",
    "",
    def.body.trimEnd(),
    "",
  ].join("\n")
}

export type SkillWrite = { name: string; path: string }

export function generateSkills(paths: Paths): SkillWrite[] {
  const written: SkillWrite[] = []
  for (const def of SKILL_DEFS) {
    const dir = join(paths.skills, def.name)
    ensureDir(dir)
    const path = join(dir, "SKILL.md")
    atomicWrite(path, renderSkill(def))
    written.push({ name: def.name, path })
  }
  return written
}

export type SkillIssue = { skill: string; code: string; message: string }

const SECTION_ORDER = ["## Goal", "## Scope", "## Execute", "## Rules", "## Expected Outcome"]

function frontmatter(text: string): { fields: Record<string, string>; related: string[]; body: string } | null {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/)
  if (!match) return null
  const fields: Record<string, string> = {}
  const related: string[] = []
  let current = ""
  for (const line of match[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z_-]+):\s*(.*)$/)
    if (kv) {
      current = kv[1]
      if (kv[2]) fields[current] = kv[2].trim()
      continue
    }
    const item = line.match(/^\s+-\s+(.+)$/)
    if (item && current === "related") related.push(item[1].trim())
  }
  return { fields, related, body: match[2] }
}

export function validateSkills(paths: Paths, knownTools: string[]): SkillIssue[] {
  const issues: SkillIssue[] = []
  const known = new Set(knownTools)
  const dirs = existsSync(paths.skills)
    ? readdirSync(paths.skills, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name)
    : []

  if (dirs.length === 0) {
    issues.push({ skill: "*", code: "missing", message: "no generated skills; run skills generate" })
    return issues
  }

  for (const dir of dirs) {
    const path = join(paths.skills, dir, "SKILL.md")
    const add = (code: string, message: string) => issues.push({ skill: dir, code, message })
    if (!existsSync(path)) {
      add("missing-file", "SKILL.md not found")
      continue
    }

    const text = readFileSyncSafe(path)
    if (text === null) {
      add("unreadable", "SKILL.md could not be read")
      continue
    }
    const parsed = frontmatter(text)
    if (!parsed) {
      add("frontmatter", "missing or malformed frontmatter")
      continue
    }

    if (parsed.fields.name !== dir) add("name", `frontmatter name "${parsed.fields.name ?? ""}" does not match directory`)
    const description = parsed.fields.description ?? ""
    if (!description) add("description", "description is required")
    else if (description.length > 100) add("description", `description is ${description.length} chars (max 100)`)

    const lineCount = text.split(/\r?\n/).length
    if (lineCount > 250) add("length", `${lineCount} lines (max 250)`)

    if (text.includes("**")) add("bold", "prohibited bold markers")

    let last = -1
    for (const heading of SECTION_ORDER) {
      const at = parsed.body.indexOf(`\n${heading}`)
      if (at === -1) {
        add("section", `missing ${heading}`)
        continue
      }
      if (at < last) add("section", `${heading} is out of order`)
      last = at
    }

    if (parsed.related.length > 15) add("related", `${parsed.related.length} related entries (max 15)`)
    for (const name of parsed.related) {
      if (!text.includes(name)) add("related", `related entry "${name}" never appears in the body`)
    }

    const toolLine = parsed.body.split(/\r?\n/).find((line) => line.startsWith("Tool list:"))
    if (!toolLine) {
      add("tools", "missing Tool list line")
    } else {
      for (const match of toolLine.matchAll(/`([a-z_]+)`/g)) {
        if (!known.has(match[1])) add("tools", `unknown tool: ${match[1]}`)
      }
    }
  }

  return issues
}

function readFileSyncSafe(path: string): string | null {
  try {
    return readFileSync(path, "utf8")
  } catch {
    return null
  }
}
