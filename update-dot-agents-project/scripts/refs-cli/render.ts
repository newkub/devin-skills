import type { Row } from './types';

function esc(v: string | number): string {
  const pipe = String.fromCharCode(124);
  const bs = String.fromCharCode(92);
  const nl = String.fromCharCode(10);
  return String(v ?? '').split(pipe).join(bs + pipe).split(nl).join(' ');
}

function rowKey(headers: string[], r: Row): string {
  return headers.map((h) => String(r[h] ?? '')).join('::');
}

export function table(headers: string[], rows: Row[]): string {
  const seen = new Set<string>();
  const unique = rows.filter((r) => {
    const key = rowKey(headers, r);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  if (unique.length === 0) return '_No entries._';
  const sorted = [...unique].sort((a, b) =>
    headers.reduce((c, h) => c || String(a[h] ?? '').localeCompare(String(b[h] ?? ''), 'en'), 0),
  );
  const lines = sorted.map((r) => '| ' + headers.map((h) => esc(r[h] ?? '')).join(' | ') + ' |');
  return [
    '| ' + headers.join(' | ') + ' |',
    '|' + headers.map(() => '---').join('|') + '|',
    ...lines,
  ].join('\n');
}

export function doc(title: string, sections: string[]): string {
  return [
    '# ' + title,
    '',
    '> Generated by refs-cli (`/update-dot-agents-project`). Do not edit manually — re-run to update.',
    '',
    ...sections,
    '',
  ].join('\n');
}
